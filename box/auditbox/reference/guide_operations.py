_CHANGE = [(g, k, label, re.compile(pattern, re.I)) for g, k, label, pattern in CHANGE_TASKS]
OPERATION_ORDER = {(g, key): index for index, (g, key, _, _) in enumerate(READ_TASKS + CHANGE_TASKS)}


def operation_for(template, purpose):
    normalized = " ".join(template.casefold().split())
    query = re.match(r"^(?:show|display|get)\s+", normalized)
    if query:
        subject = normalized[query.end():]
        # A few existing excerpts have a neighboring command's paragraph. Do
        # not disguise that as a reviewed operation. The raw fact is retained.
        if subject == "aaa configuration" and not re.search(r"aaa|authenticat|authoriz|accounting|认证|授权|计费", purpose, re.I):
            return None
        if subject == "logging configure" and re.search(r"records|日志.*记录", purpose, re.I):
            return "fault", "log-records", "查看日志记录"
        patterns = _READ
    else:
        if re.fullmatch(r"version <[^>]+>", normalized):
            # Protocol-version settings must not inherit the broad software
            # version label from a manual's keyword annotation.
            if re.search(r"(?<![a-z])rip(?:-\d)?(?![a-z])", purpose, re.I):
                return "routing", "rip-version", "设置 RIP 协议版本"
            if re.search(r"\bmstp\b|\bmst\b.*version", purpose, re.I):
                return "fault", "mstp-version", "设置 MSTP 协议版本"
        if normalized == "exit" and re.search(r"退出登录|退出.*设备|log\s*out", purpose, re.I):
            return "configuration", "logout", "退出设备登录"
        if normalized == "who":
            return "security", "users", "查看已登录用户"
        subject, patterns = normalized, _CHANGE
    for group, key, label, pattern in patterns:
        if pattern.fullmatch(subject):
            return group, key, label
    return None
